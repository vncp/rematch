#!/bin/sh
# Regenerates docs/book/src/reference/cli.md from the binary's own `--help` output:
# `rematch --help`, then every subcommand listed under "Commands:", recursively.
#
#   sh docs/book/gen-cli.sh                     # uses target/release/rematch
#   REMATCH_BIN=target/debug/rematch sh docs/book/gen-cli.sh
#
# Run it after any change to the clap definitions (crates/rematch/src/main.rs) and commit
# the result. `--help` never opens the ledger; REMATCH_ROOT points at an empty temp dir anyway.
set -eu

here=$(cd "$(dirname "$0")" && pwd -P)
repo=$(cd "$here/../.." && pwd -P)
bin=${REMATCH_BIN:-$repo/target/release/rematch}
out=$here/src/reference/cli.md

[ -x "$bin" ] || { echo "gen-cli: $bin is not executable (cargo build --release, or set REMATCH_BIN)" >&2; exit 1; }

REMATCH_ROOT=$(mktemp -d)
export REMATCH_ROOT
trap 'rm -rf "$REMATCH_ROOT"' EXIT

# Subcommand names listed under "Commands:" of one help text (clap indents each by two spaces).
subcommands() {
	awk '/^Commands:/ { f = 1; next } f && /^$/ { exit } f && /^  [a-z]/ { if ($1 != "help") print $1 }'
}

# Heading per depth: `rematch lake` is "##", `rematch lake export` "###".
emit() {
	local path=$1 depth=$2 help hashes sub
	help=$("$bin" $path --help)
	hashes=$(printf '%*s' "$depth" '' | tr ' ' '#')
	printf '%s `rematch%s`\n\n```text\n%s\n```\n\n' "$hashes" "${path:+ $path}" "$help"
	for sub in $(printf '%s\n' "$help" | subcommands); do
		emit "${path:+$path }$sub" $((depth + 1))
	done
}
version="rematch $("$bin" --version | sed -n 's/.*"version":"\([^"]*\)".*/\1/p')"
tmp=$out.tmp
{
	printf '# CLI reference\n\n'
	printf '<!-- Generated by docs/book/gen-cli.sh from `%s`; do not edit by hand. -->\n\n' "$version"
	printf 'Every subcommand prints one JSON envelope on stdout (`{"ok":true,"operation":…,"data":…}`, exit 0; `{"ok":false,…,"error":…}`, exit 1; 2 on a usage error; 130 when cancelled) unless `--text` asks for readable lines (DESIGN §2). The sections below are the binary'"'"'s own `--help` output (%s), one per subcommand.\n\n' "$version"
	printf '## Commands\n\n'
	"$bin" --help | subcommands | while read -r sub; do
		printf -- '- [`rematch %s`](#rematch-%s)\n' "$sub" "$sub"
	done
	printf '\n'
	help=$("$bin" --help)
	printf '## `rematch`\n\n```text\n%s\n```\n\n' "$help"
	for sub in $(printf '%s\n' "$help" | subcommands); do
		emit "$sub" 2
	done
	printf -- '---\n\nSource: `rematch --help` and `rematch <command> --help` (%s), generated by `docs/book/gen-cli.sh`; envelope and exit codes: docs/DESIGN.md §2.\n' "$version"
} >"$tmp"
mv "$tmp" "$out"
echo "gen-cli: wrote $out ($version)"
